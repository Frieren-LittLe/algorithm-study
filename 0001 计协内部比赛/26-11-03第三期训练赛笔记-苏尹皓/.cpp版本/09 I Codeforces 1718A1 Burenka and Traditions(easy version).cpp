#include<iostream>
#include<set>
using namespace std;

// 解本题需要了解 "异或前缀和" 的概念
// 先看本文件夹中的【异或前缀和.md】

// 本题是一道非常经典的"异或性质+贪心"题
// 题意:使区间[l,r]内的数都乘上x，消耗(r-l+1)/2的代价，使其变为0，求让整条数列变为0消耗的最少代价
// 可以发现一个区间都可以等价拆分为若干长度为1 或 2 的操作，代价不变

// 所以，我们只用两种操作,且每次只消耗一次代价:
// 1.单点清零:选一个数异或上专门定制的x，使其变成0
// 2.相邻打包:选相邻的2个数，同时异或同一个数x

// 因为异或的自反性，一段区间内长度为2的操作(乘两遍x)改变不了该区间的总异或和
// 设区间[a1,a2,...,ak]的总异或合恰好等于0，即a1^a2^...^a(k-1)^a(k) = 0
// 然后从左往右做k-1次长度为2的操作，每次都把左边那个数清零:
// 第一步:让(a1,a2)同时异或当前的a1，a1变成0
// 第二部:让(a2,a3)同时异或当前的a2, a2变成0
// ...
// 第k - 1步，让(ak-1,ak)同时异或当前的ak-1，则ak-1变成0
// 此时数组为[0,0,0,...,0，最后的ak]，不过异或和仍为0，唯有0^0 = 0,因此ak的值自然为0
// 那么我们可以发现，原先裁成每个数成分别的x需要消耗k次代价
// 此时优化到了k-1次
// 也就是说，每当我们发现总异或和的为0的子区间，就可以减少一次代价,这就是本题核心的优化思路

void solve() {
	int n;
	cin >> n;

	set<int> seen;
	seen.insert(0);
	// 设一个初始前缀异或和 P_0 = 0;
	// 用来抓从当前段开头算起总异或和刚好变成 0 的区间（含单个 0），防止漏算

	int px = 0;		// 当前前缀异或和
	int saved = 0;	// 最多能够省下的操作次数

	for (int i = 0;i < n;i++) {
		int x;
		cin >> x;
		px ^= x;

		if (seen.count(px)) {
			// 当【之前遍历过的异或和】和【当前遍历到的异或和】相同 时，视作发现一个异或和为 0 的区间，立刻贪心切分
			saved++;
			// 重置集合，准备寻找下一个互不相交且异或和为0的区间

			// 若两个区间相交，其中一个区间的值全部定为0之后
			// 另一个区间再从头到尾进行传导操作势必会使得两个区间的共同子区间消耗更多的代价，得不偿失
			seen.clear();
			px = 0;
			seen.insert(px);
		}
		else {
			seen.insert(px);
		}
	}
	cout << n - saved << '\n';
}

int main() {
	ios::sync_with_stdio(false);
	cin.tie(nullptr);

	int t;
	cin >> t;
	while (t--) {
		solve();
	}
	return 0;
}