#include <iostream>
using namespace std;
int main() {
	int n;
	cin >> n;
	int d = 0, i = 0;
	while (n > 0) {
		d++;
		if (i == 0 && n % 3 == 1)
			i = d; // 当天数n为3的倍数+1时，说明此时n会被挑出来
		// 设一个d对n的刷新次数计数，被挑出来时即可判断出是第几轮
		n = n * 2 / 3;
		// 每挑完一次，n就减少[n/3]个苹果
		// 我们要×原来的2/3，但是减少的苹果向上取整多拿了
		// 所以剩下的苹果要向下取整，先乘2是为了方便最后砍小数
		// 如果非要先除以3，表达式会写成
		// n = n / 3 * 2 + n % 3 * 2 / 3

		// 如果写成减法形式，可以写成t = t - (t + 2) / 3
	}
	cout << d << ' ' << i << endl;
	return 0;
}