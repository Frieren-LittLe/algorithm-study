#include<iostream>
using namespace std;
// 本题的s和S(s)不要区分错了
// s是a1 + a2 + ... + an
// S(a)是a1 ^ a2 ^ ... ^ an

// 异或和为0，意味着S(a)的二进制格式中的每位数都为0
// 异或的运算:0^0 = 0，1^1 = 0, 1^0 = 1 ，由此可观,为使每二进制位数都是0:
// 在每一个二进制位上，数列里所有元素中1的个数都必须是偶数
int main() {
	int t;
	cin >> t;
	while (t--) {
		long long s, m;
		cin >> s >> m;

		if (s % 2 == 1 || m < 2) {
			// 题目要求s >= 1,一个正数的异或和就是它自己，S(a)绝不可能等于0

			// "由所有元素中1的个数都必须是偶数"，及"奇数最小二进制位数为1，偶数最小二进制位数为0"的性质可知
			// 组成S(a)的元素中，奇数项的个数必须是偶数
			// 组成S(a)的元素同时也为组成s的元素，由s的公式可知s为偶数，不可为奇数
			cout << -1 << '\n';
			continue;
		}
		// 满足以上两个条件时，我们很容易就能想到构造a = {s/2 , s/2}
		// 它满足:长度为2 <= m,两个元素都大于等于1，且不超过s
		// 元素之和: s/2 + s/2 = s;
		// 异或和为: (s/2) ^ (s/2) = 0
		// 所有条件均满足，因此一定有解
		cout << 2 << ' ' << s / 2 << ' ' << s / 2 << '\n';
	}
	return 0;
}