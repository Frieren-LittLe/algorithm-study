#include<iostream>
using namespace std;
// 题面中的三个条件可以压缩成:
// 每个三明治至少要有一根及以上香肠和至少比香肠数量多一块的奶酪

// 可以看出这题就是一道木桶效应题，一个木桶能装多少水，取决于最短的那块木板
// 当奶酪数量是香肠两倍以上时，被香肠数量卡死，此时汉堡数量为香肠数量
// 当奶酪数量小于香肠两倍时，会被奶酪数量卡死，此时汉堡数量为奶酪数量-香肠数量

// a >= 2b 左右减b 为 a - b >= b
// 当奶酪数量-香肠数量多余香肠数量时，此时汉堡数量为香肠数量
// 当奶酪数量-香肠数量少于香肠数量时，此时汉堡数量为奶酪数量-香肠数量
// 也就是说 汉堡数量为min(奶酪数量-香肠数量，香肠数量)

// 为什么会想到左右减去b？
// 因为a >= b+b(一个b是基础的数量，另一个b是输出b时a-b至少溢出的数量)
// 都减去基础的数量能得到a-b >= b (a-b实际多出的数量和输出b时a-b至少溢出的数量)
int main() {
	int t;
	cin >> t;
	while (t--) {
		int a, b;
		cin >> a >> b;
		int ans = min(b, a - b);
		cout << ans << endl;
	}
	return 0;
}