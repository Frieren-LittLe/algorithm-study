#include<iostream>
using namespace std;

int main() {
    long long n, p, k;
    // 第一次从A_0射到A_p，位移了p位
    // 在圆中的反射特性就是，每次反射光线的圆周角都是相同的，每次的位移也是相同的

    // 接下来k-1次加上已经发生的A_0到A_p的那一次，总共发生了k次位移
    // 总位跨过的等分点数目为p*k

    // 位移超过n位时就到了新的一圈，既然有n个等分点，光线位移的单位也是等分点，需要对n取模

    // 抵达的终点位置为(p*k)% n
    // 但是p，n的数据范围皆为10^9，直接相乘最高为10^18，会爆int数值
    // 可以让p,k取模之后再相乘,然后再取模一边，结果不变，数值占用率则小了
    // 养成防溢好习惯
    cin >> n >> p >> k;
    long long ans = (p % n) * (k % n) % n;
    cout << ans << endl;
    return 0;
}