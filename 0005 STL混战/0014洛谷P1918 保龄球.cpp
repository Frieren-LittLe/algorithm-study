#include<iostream>
#include<map>
using namespace std;
// map可以看作是算法题里专门用来解决"定义域(key)很大，但实际出现的元素(value)个数很少"的键值反转神器
// 【26-11-10计协第四期比赛的第6题CF 1742D】有详细讲解何为"键值反转"

// 本题m的取值范围为1~1e9，n的取值范围为1~1e5
// 本题要求我们输出[打倒m个瓶子]对应的[发球位置]
// 常规思路为用[发球位置]作为数组底标存[该位置可以打倒的瓶子数量]
// 但是题面求 q(最高1e5)次:给出[要打倒瓶子数量]，求对应的[发球位置]
// 不可能开一个for循环来遍历[发球位置]来判断哪个会为所求m吧?(除非使用二分法+离散化)

// 于是我们采用"键值反转"
// 即用[该位置可以打倒的瓶子数量]作为数组底标存[发球位置](本题保证各个位置的瓶子数不同)
// 这样"给出[要打倒瓶子数量]，求对应的[发球位置]"就是一个cout的事了
// 容器不宜选择vector,因为vector是连续的，m最大为1e9,也就是说要开1e9个位置，一个位置消耗4byte，算下来最大需要3.8G的内存
// 本题的内存限制为128MB，用vector开会直接导致MLE！
// 但是map容器是不连续的，需要哪个键才开哪个键，最多开1e5个位置，大概390KB，完全存得下
int main() {
	ios::sync_with_stdio(false);
	cin.tie(nullptr);

	int n;
	cin >> n;

	map<int, int>mp;

	for (int i = 1;i <= n;i++) {
		int x;
		cin >> x;
		mp[x] = i;
		// 键值反转
	}
	int q;
	cin >> q;
	while (q--) {
		int m;
		cin >> m;
		cout << mp[m] << '\n';
	}
	return 0;
}