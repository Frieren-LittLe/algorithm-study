#include<iostream>
using namespace std;
//这题不让我们用for和while建立循环语句完成这个题目
//我们可以尝试构建一个阶乘函数来完成这一题
int F(int n) {
	if (n == 1) {
		return 1;
	}//当n为1时，返回值为1
	return n * F(n - 1);//否则，令n乘以F(n-1)，你没看错，在构建一个函数的同时，我们可以直接引用当前构建的函数
	//把所有的F（）展开后，我们就能得到n×(n-1)×(n-2)...3×2×1这样的阶乘公式
}
//在函数内部引用该函数的行为就是嵌套，嵌套是可以实现循环计算的一种方式
int main() {
	int n;
	cin >> n;
	//初始化一个数n，从键盘读取一个数存入其中
	cout << F(n) << endl;
	//向F()的小括号中加进n求得返回值
	return 0;
}