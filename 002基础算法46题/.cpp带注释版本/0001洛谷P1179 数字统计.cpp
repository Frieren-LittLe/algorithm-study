//步入基础算法，我们要有时间复杂度的概念
#include<iostream>
using namespace std;
int main() {
	int L, R;
	cin >> L >> R;

	// 算法分析均按“最坏情况（极值）”评估：假设 L = 1，R = 100000
	int ans = 0;
	// 从 L 递增枚举到 R，总共遍历的整数个数为：R - L + 1
	// 最坏情况下：遍历 1 到 10^5，外层循环跑满 100,000 次（10^5 轮）
	for (int i = L;i <= R;i++) {
		// 保护当前循环坐标 i，引入副本 t 进行拆位检验
		int t = i;
		while (t > 0) {
			if (t % 10 == 2) {
				// 不断 / 10，规模缩减需 log10(10^5) 步，内层极值仅跑 6 次
				// 可以省略记为 log N
				// 综合外层：外层 N 轮 × 内层 log N 步，总时间复杂度即 O(N * log N)
				ans++;
			}
			t = t / 10;
		}
	}
	// 验证算法是否不超时的两种办法：
	
	// 方法一：正向精算法（代入极值算具体步数）
	//   - 最坏情况循环总轮数 ≈ 10^5 (个数) × 6 (位数) = 6 × 10^5 次
	//   - CPU 基本运算总步数 ≈ 6 × 10^5 × 4 ≈ 2.4 × 10^6 次（约 240 万次）
	//   - 评测机 1 秒安全线约为 10^8（1 亿次）：
	//     2.4 × 10^6 << 10^8，仅占 1 秒预算约 2.4%，耗时约 2~10ms，稳过
	
	// 方法二：反向查表法（看数据规模 N，对照允许复杂度）
	//   - 设区间长度 N = R - L + 1 <= 10^5
	//   - 查对照表：当 N 达到 10^5 ~ 10^6 规模时，1 秒时限允许的最大复杂度为 O(N log N) 或 O(N)
	//   - 本代码时间复杂度为 O(N log N)
	//   - 结论：复杂度恰好落在安全区间内，不需要降维优化，直接判定通过
	cout << ans << endl;
	return 0;
}
// 枚举本质：“不漏掉任何一种可能，挨个拿来检验”
// 为什么本题敢枚举：通过前面精算，总步数仅 2.4×10^6 << 10^8
// 运算量远没达到 1 秒上限，暴力穷举就是最简单稳健的最优解