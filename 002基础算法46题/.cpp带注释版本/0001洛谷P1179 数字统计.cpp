// 2. 本题三大要素对应：
//    - 解空间（候选范围）：区间 [L, R] 里的每一个离散整数
//    - 枚举顺序：for 循环从小到大依次遍历，保证“不重、不漏”
//    - 检验准则：副本 t 逐位拆解判断末位是否为 2，命中则累加
// 3. 为什么敢枚举：通过前面精算，总步数仅 2.4×10^6 << 10^8
//    运算量远没达到 1 秒上限，暴力穷举就是最简单稳健的最优解
