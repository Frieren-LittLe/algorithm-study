#include<iostream>
#include<algorithm>
using namespace std;
int main() {
	int n, m;
	cin >> n >> m;
	int p[2048];
	// n: 草料总数, m: 买家总数
	// p[]:用来存放每个农夫出的价钱
	for (int i = 0;i < m;i++) {
		cin >> p[i];
	}
	// p最多为1000，存入数组这一步消耗了1k次"操作"

	sort(p, p + m,greater<int>());
	// 将农夫的出价由大到小排序
	// 之前的笔记内容我们已经知道了sort(起始点,终止点) 的格式是由小到大排序
	// 而 sort(起始点,终止点,greater<>()) 的格式是由大到小排序
	 
	 
	// 1，为什么从大到小排序？
    // 排完后，如果把售价定为第 i 个人的出价 p[i]
    // 那么前面出价更高的所有人（共 i + 1 人）必然都买得起，直接免去内层统计
    // 运算量：快排约为 m * log2(m) ≈ 1000 * 10 = 10,000 次操作
	 
	// 2，为什么sort M个数时，消耗的操作次数是M * log2（M）？
	// 快速排序每次挑选一个基准数，把所有数分成两堆：比它小的放左边，比它大的放右边
	// 我们当作sort 每次把数据对半砍，M 连续除以 2 砍到只剩 1 个，刚好切 log2(M) 轮
	// 每一层都需要把所有m个数遍历一遍，来比较它们与基准数的大小，总运算量为M*log2(M)

	// 3，基准数如何得来的？
	// 拿出最左端、最右端、正中间这三个数
	// 进行 2~3 次比较，挑出这三者里的大小居中者作为基准数
	// 代价极小，但极大降低了选到极值的概率
	int limit = min(n, m);
	// 2. 有效销售上限
	// 草料只有 n 批，买家就算再多，最多也只能卖出 min(n, m) 批

	// min(x,y)源于algorithm,可以将(小括号)里的两个数相互比较，并得出最小值
	// 注意一次只能比较两个数，如果要比较三个数，可以使用嵌套的做法，如min(min(x,y)z)这样就可以比较出三个数的最小值
	// 其实还有一个作用相反的函数max（x，y），它可以得出两个数其中的更大的值

	int ans1 = 0;// 记录最优单价
	int ans2 = 0;// 记录最大总收入
	for (int i = 0;i < limit;i++) {
		int sum = (i + 1) * p[i];
		// 购买人数（底标+1）×单价 =收入
		if (sum >= ans2) {
			ans2 = sum;
			ans1 = p[i];
			// 核心细节：题目要求“赚的钱相同时，输出更低的价格”。
			// 因为是从大到小排的，后面的价格肯定更便宜；
			// 用 >= 可以在收入持平时，自动用后面更低的价格覆盖前面的。
		}
	}
	cout << ans1 << " " << ans2 << endl;
	return 0;
}

// 4. 总运算量精算与时限比对

//	正向：
// - 读入：约 1,000 次
// - 排序：约 10,000 次
// - 枚举：约 1,000 次循环 × 3 次判断赋值 ≈ 3,000 次
// 总计算量 ≈ 1.4 × 10^4 次 << 评测机 1 秒的 10^8 阈值，耗时约 1ms 瞬间跑完
	 
//	反向：	
// 整体时间复杂度：O(m log m)，对应的典型数据规模上限为N <= 10^5 ~ 10^6，而该题仅为10^4