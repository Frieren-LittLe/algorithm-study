#include<iostream>
using namespace std;
// 这道题是经典的前缀和示例题
// 如果用传统做法来写，
// 读入所有a[i],进行m次循环，每次循环让从左端到右端的所有a[i]相加
// 计算量为10^5*10^4 = 10^9,大于10^8的安全线，TLE！

// 我们可以不用记录a[i]，先初始化s[0]=0，每次的a[i]都直接加到s[i]里
// 记录下从0到当前的下标的数值之和
// 求某一区间的和只需右端点减去左端点左边的一位数就可以通过一次运算得到，不必经过再一次的累加
// 这样的话，时间复杂度从O（n^2）降低到O(m+n),计算量也从10^8降低到10^5,通过
// 这就是前缀和算法

// 像是求某个区间的和的题，优先考虑前缀和优化时间复杂度
const int N = 1e5 + 5;
long long s[N];

int main() {
	int n, m;
	cin >> n;
	for (int i = 1;i <= n;i++) {
		int x;
		cin >> x;
		s[i] = s[i - 1] + x;
	}
	// 这一步也叫预处理，即先把和给算出来，避免后续在内部循环求和
	cin >> m;
	for (int i = 1;i <= m;i++) {
		int l, r;
		cin >> l >> r;
		cout << s[r] - s[l - 1] << '\n';
	}
	return 0;
}