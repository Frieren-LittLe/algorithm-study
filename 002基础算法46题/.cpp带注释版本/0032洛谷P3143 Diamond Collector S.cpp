#include<iostream>
#include<algorithm>
using namespace std;
// 如果本题只有一个柜子的话，只需设立两个指针
// 通过打擂台法遍历并判断左右指针之间的最大区间段长度，就能轻而易举地解出本题的答案

// 但这题有两个柜子：不妨枚举分界线 i，把数组切成 [1..i] 和 [i+1..n] 两段，
// 前段用 pre[i] 求柜1能放的最大数量，后段用 suf[i+1] 求柜2能放的最大数量，两者相加即为该分界下的总数

// 本题我们将钻石从小到大排序，并将其放入两个柜子
// 两个柜子可视作：一个放整体较小的钻石段，另一个放整体较大的钻石段
// 排序后每个柜子必是连续段，若两段交叉则交换交叉部分即可保持合法且总数不变，故总可化为前后不交叉

const int N = 5e5 + 10;
int n, k;
int a[N];
int pre[N];// pre[i]: 前 i 颗钻石中，能放进一个柜子的最大数量
int suf[N];// suf[i]: 从第 i 颗到最后一颗钻石中，能放进另一个柜子的最大数量

int main() {
	ios::sync_with_stdio(false);
	cin.tie(0);

	cin >> n >> k;
	for (int i = 1;i <= n;i++) {
		cin >> a[i];
	}
	sort(a + 1, a + 1 + n);
	// 排序后，同一个柜子里选的钻石在数组中一定是连续的一段
	// sort存在的话，排序步骤的时间复杂度就为n*logn

	int j = 1;
	// 设窗口左边界为1
	for (int i = 1; i <= n;i++) {
		// 右边界从1到n不断地遍历
		// 当当前遍历的右边界与左边界的差值大于k时，左边界右移
		while (a[i] - a[j] > k) {
			j++;
		}
		pre[i] = max(pre[i - 1], i - j + 1);
		// 当前遍历的右边界的pre值，即当前i值第一个柜子可以放的最大数量
		// 要么继承之前已经有过的更长的值，要不然为当前[j,i]区间段的长度
	}
	
	// 接下来原模原样的式子倒过来，就可以求suf[i]了

	j = n;
	// 设窗口右边界为n
	for (int i = n;i >= 1;i--) {
		// 从n到1不断地拓展并遍历左边界
		while (a[j] - a[i] > k) {
			j--;
			// 当当前遍历的右边界与左边界的差值大于k时，右边界左移
		}
		suf[i] = max(suf[i + 1], j - i + 1);
		// 当前遍历的右边界的suf值，即当前i值第二个柜子可以放的最大数量
		// 要么继承之前已经有过的更长的值，要不然为当前[i,j]区间段的长度
	}
	int ans = 0;
	for (int i = 1;i < n;i++) {
		ans = max(ans, pre[i] + suf[i + 1]);
		// 以 i 为界，前段给柜1、后段给柜2，取两段最大和
	}
	cout << ans << endl;
	return 0;
}
// 枚举分界线是这类"把数组切成两段、两段各求最优再合并"问题的通用套路
// 把整体问题拆成"前段最优 + 后段最优"，然后枚举所有切法取最大值