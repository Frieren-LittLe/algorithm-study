#include<iostream>
#include<algorithm>
using namespace std;
// 凡是涉及"寻找满足特定条件的连续子数组（或区间）"的问题
// 通常都可以优先考虑使用"滑动窗口（同向双指针）"算法
// 滑动窗口法其实是一种用双指针思想优化过的枚举法

const int N = 1e6 + 10;
const int M = 2010;
// 用 const 保证 N,M 定义后不可修改（只读）,以便可以将N,M当常量使用
// 因此才可以int a[N],b[M]
int a[N];// 用于存放图画
int b[M];// 用于记录画师在已有窗口里面的出现次数
int n, m;

int main() {
	cin >> n >> m;
	for (int i = 1;i <= n;i++) {
		cin >> a[i];
	}
	int l = 1, r = 0;
	// 设置好窗口的左右两端
	int cnt = 0;
	int ans = N;
	// 设置初始的答案的最小可能值为N，一旦在滑动过程中发现更小的符合条件的答案就顶替掉已有答案(打擂台法)
	int ansL = 1, ansR = n;
	// 设置输出的答案左右端为l和n,在更新最小值的过程中一并更新最小可能情况的左右端点
	while (r < n) {
		r++;
		// 右端点不断增加
		if (b[a[r]] == 0)cnt++;
		// 一旦发现当前数组b中这个画师没有被标记，则记录当前窗口中已有的不同画师数目+1
		b[a[r]]++;
		// 记录当前画师出现的次数+1
		while (cnt == m) {
			// 当计数攒勾m，也就是窗口中已经有了m个画师了，就判断此时的答案是否比之前的情况小
			// 如果比之前的情况小就更新答案
			
			// 然后再让最左端的画师计数减小1，如果这个画师出现次数仍然不为零，继续while循环并更新答案
			// 如果这个画师出现次数归零了，就左移左端点，并使cnt计数减小，继续向右遍历到cnt重回到m

			// 当r = n碰壁时，循环终止
			if (r - l + 1 < ans) {
				ans = r - l + 1;
				ansL = l;
				ansR = r;
			}
			b[a[l]]--;
			if (b[a[l]] == 0)cnt--;
			l++;
		}
	}
	cout << ansL << " " << ansR << endl;
	return 0;
}