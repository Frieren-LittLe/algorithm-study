#include<iostream>
#include<vector>
#include<algorithm>
using namespace std;
// 递归是"函数调用自己、自顶向下分解"
// 递推是"循环利用已知项、自底向上推导"
// 二者常可互相转化，递推通常是递归的迭代优化形式

// 对于洛谷 P1255 这道题，必须使用高精度加法:
// 题目中 N 最大为 5000，而数楼梯的结果是斐波那契数列的移位版本
// 斐波那契数列增长极快，第 5000 项大约是F(5000) ≈ 1.4 × 10^1044,结果有 1000 多位数字

// 为了方便后续的加法运算，将加法的底层独立写出来单开一个分函数
vector<int> add(vector<int>& a, vector<int>& b) {
	// 在引用变量到分函数中运用时，常规的 （变量类型 变量名）写法会直接拷贝一遍到该分函数中
	// 如果引用的变量在接下的步骤中不会发生修改，则没有必要拷贝，冗余的运算步骤，效率会很低
	// 加&，可以避免拷贝，直接引用，增强效率
	vector<int> c;
	int carry = 0;

	for (int i = 0;i < a.size() || i < b.size() || carry;i++) {
		// 当一个条件为"变量名"的格式时，等价于"变量名 ！= 0"
		if (i < a.size()) carry += a[i];
		if (i < b.size()) carry += b[i];

		c.push_back(carry % 10);
		carry /= 10;
	}
	return c;
}
// 有时候vector小括号内表示的是数组的最大大小
// 当小括号后出现了大括号并且大括号内含有运算步骤时，小括号内就是引用到的变量

int main() {
	int n;
	cin >> n;
	
	vector<int> f[3] = { {1},{1},{} };
	// 建立一个滚动数组，
	// 何为滚动数组:
	// 用固定大小的数组，通过取模运算循环利用空间，从而把 O(n) 的空间压缩到 O(k)，且k<n
	
	// 斐波那契数列就是典型的循环数组,本题也正是斐波那契数列思想的运用题
	// 即a_n = a_(n-1) + a_(n-2)
	// 因为我们并不需要保留所有的数据，只需要三个空间，两个空间用来读数据，一个空间用来求新的数据就行了
	// 初始情况下我们设前两格为1，第一次运算答案填第三格
	// 第二次运算引用第二格和第三格的数值，计算出来填到第一位(覆盖掉之前的第一位)，依此循环
	for (int i = 2; i <= n;i++) {
		f[i % 3] = add(f[(i - 1) % 3], f[(i - 2) % 3]); // 将参数引入至add分函数中进行高精度加法运算
		// 第一次运算,f[2] = f[1] + f[0] = 2;
		// 回过头来想为什么初始1，1，0
		// 爬上第二层方式有两种
		// 1，第一层爬到第二层消耗的步数为1
		// 2，第零层爬到第二层消耗的步数为1
	}
	vector<int>& ans = f[n % 3];

	for (int i = ans.size() - 1;i >= 0;i--) {
		cout << ans[i];
	}
	return 0;
}