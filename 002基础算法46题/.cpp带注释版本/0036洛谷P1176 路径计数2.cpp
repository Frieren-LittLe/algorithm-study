#include<iostream>
using namespace std;
// 如果没有障碍物，这题就变成了一个纯数学组合问题
// 从(1,1)到(N,N)，需要走:
//		向下N-1步	+	向右N-1步	
// 一共有C(2N-2,N-1)种组合方式，总共走(2N-2)!/[(2N-2)!(N-1)!]步

// 但这题存在障碍物，且不能简单地减去跟这个障碍物关联的路线
// 因为障碍物之间的路径会重叠，需要用到容斥原理

// 因为只能向右和向下走
// 从原点出发，抵达某一格子可能的路径数目恰等于抵达其上方一格和其左方一格的路径数目之和
// 发现该规律恰好符合递推的特征

const int mod = 100003;
int dp[1005][1005];// 存储路径数，障碍物用特殊值标记
int n, m;

int main() {
	cin >> n >> m;
	for (int i = 1;i <= m;i++) {
		int x, y;
		cin >> x >> y;
		dp[x][y] = -1;
		// 标记障碍物，这里用-1表示障碍
	}

	if (dp[1][1] == -1) {
		cout << 0 << endl;
		return 0;
		// 注意本题范围中，起点也是有可能出现障碍的
		// 一旦本题的起点存在障碍，直接输出0，结束程序
	}
	dp[1][1] = 1;
	// 将起点标记为1，开始递推/迭代
	for (int i = 1;i <= n;i++) {
		for (int j = 1;j <= n;j++) {
			if (i == 1 && j == 1) continue;
			// 自上向下地自左向右开始遍历，若当前值已被标记为1，跳过
			// (算法竞赛中默认x正半轴朝下，y正半轴朝右)
			if(dp[i][j] == -1) {
				dp[i][j] = 0;
			}
			// 如果遍历到障碍物，将障碍物点的路径数量填为0
			else {
				// 当前一格的路径数为 上方一格的路径数 + 左侧一格路径数 
				int fromUp = (i > 1) ? dp[i - 1][j] : 0;
				int fromLeft = (j > 1) ? dp[i][j - 1] : 0;
				dp[i][j] = (fromUp + fromLeft) % mod;
			}
		}
	}
	cout << dp[n][n] << endl;
	return 0;
}