#include<iostream>
using namespace std;
int f[1005];
// 这题如果暴力递归(由大往小求),写法大概是
// f(n) = 1 + f(1) + f(2) + ... + f(n/2)
// 时间复杂度为O(2^n)指数级的级别，2^100相当于10的30次方，耗时远超宇宙年龄

// 我们考虑使用递推算法优化，观察到:
// 若i为奇数，f(i) = f(i-1)
// 若i为偶数，f(i) = f(i-1)+f(i/2)
// 尽管排列时的排法中排头的数都不一样，但是排法的数目确实是满足该公式的
// 如果将排头的几位数都定住，那么剩下的数排的方式不久和没有顶住的几位数排的方式一样吗？
// 所以我们可以依次算法，从小往大将该公式写出来，并推出想要的答案
int main() {
	int n;
	cin >> n;
	f[1] = 1;
	for (int i = 2;i <= n;i++) {
		f[i] = f[i - 1];
		// 先继承，代表“把 i 当成 i-1 来看”的那部分方案
		// 奇数i和它前面的偶数i-1，在构造数列时能添加的数是一样的
		if (i % 2 == 0) {
			f[i] += f[i / 2];
			//偶数 i 比它前面的奇数 i-1 多了一个可选的第二位数 i/2，而这一类方案的数量正好是 f(i/2)
		}
	}
	cout << f[n];
	return 0;
}