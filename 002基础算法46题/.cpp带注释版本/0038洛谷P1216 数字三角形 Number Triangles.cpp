#include<iostream>
#include<algorithm>
using namespace std;

int a[1005][1005];
// 经过前面几题的训练，这题我们看一眼就知道是个递推经典题
// 别把这题当等腰三角形看，当作样例中的直角三角形看

// 我们的最终答案是一个最大值
// 如果从上往下推就是纯暴力搜索，会得到多个值，路径数目逐渐增加，还要比较出最大值

// 全局情况中 从最下往上走的最大路径和，等于从上往下走的最大路径和
// 于是我们从下往上推，从倒数第二行开始，逐行向上处理
// f[i][j] += max(f[i+1][j],f[i+1][j+1])
// 每个位置更新后，它的值代表的是「从这个位置出发走到最底部的最大路径和」
// 而且越往上走一层，就越缩小路径的数目
// 当推到顶点时，a[0][0] 自然就是「从顶点出发到底部的最大路径和」

int main() {
	int r;
	cin >> r;

	for (int i = 0;i < r;i++) {
		for (int j = 0;j <= i;j++) {
			cin >> a[i][j];
		}
	}

	for (int i = r - 2;i >= 0;i--) {
		for (int j = 0;j <= i;j++)
			a[i][j] += max(a[i + 1][j], a[i + 1][j + 1]);
	}
	cout << a[0][0] << endl;
	return 0;
}