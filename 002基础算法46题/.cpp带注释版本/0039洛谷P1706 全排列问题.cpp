#include<iostream>
#include<iomanip>
using namespace std;
// "搜索"（Search）是指在某个数据结构或解空间中查找满足特定条件的元素/路径/方案的过程
// BFS 和 DFS 是"状态空间搜索"中最基础的两大遍历策略，它们回答的是同一个问题：如何系统地访问搜索树/状态图中的所有节点

// 本题是一个DFS模板题，DFS全称Depth-First Search —— 深度优先搜索（深搜）
// DFS 优先向"深"处扩展，沿一条路径一直走到底
// 走不通（或到达终点/叶子）就回溯到最近一个还有未访问分支的节点
// 当这个分叉的所有分支都遍历完全时，再继续回溯到更上一层的分叉，直到整棵搜索树/图遍历完毕
// 洛谷P 1706这题要求我们将所有可能的排列方式罗列出来
// 可以利用"沿一条路径走到底，走不通再回溯"的dfs思想做出这道题
int n;
int ans[10];	// 存放当前排列
bool used[10];	// 标记数字是否已被使用

// dfs常用"递归"的方式实现回溯(外层函数包裹一个或多个内部递归函数，结构上天然适合dfs)
// 递归：一个函数直接或间接地调用自己

// 本题的dfs+递归解题思路:
// 设置一个dfs分函数，在函数内部:
// 设置一个输出数组用于固定数据，当数据的数目达标时将其输出(每一层dfs可以固定一个ans，最后一层dfs用于输出)
// 并设置一个标记数组用于标记已经被固定的数据，保证数据单一性
// 用for循环遍历到尚未被固定的数据，固定到输出数组，再进入到下一层dfs函数,不断固定
// 输出结束后，返回上一层dfs的for循环，若上一层的dfs的for循环也完毕，退回上层的上层的for循环，以此类推

void dfs(int step) {
	// 已经填满n个位置，输出当前排列
	if (step == n + 1) {
		for (int i = 1; i <= n;i++) {
			cout << setw(5) << ans[i];
		}
		cout << endl;
		return;// return可以结束掉这一层的dfs,回溯到上一层的dfs 
	}
	for (int i = 1;i <= n;i++) {
		if (!used[i]) {
			used[i] = true;		// 标记已使用
			ans[step] = i;		// 填入当前数字
			dfs(step + 1);		// 递归填下一个位置
			used[i] = false;	// (上一步骤的dfs填满之后)回溯，撤销标记
		}
	}
	return;	// 这里一个return其实可以省略
			// 这里保留方便理解for循环结束后函数跳回上一层dfs
	
	// 比如说，第一次我们填入的数的顺序为1,2,3,4,5
	// 然后回溯，将数字5移出来used[5] = false，回到dfs(5)
	// 发现此时的for循环也已经结束了，回溯到上一层dfs,也就是dfs(4)
	// 然后将used[4] = false，此时for循环到了5，使得ans[4]输入5
	// 然后进行dfs(5),在dfs(5)中的for循环遍历到4，使得ans[5]填入4，这样就是1,2,3,5,4
}

int main() {
	cin >> n;
	dfs(1);
	// 从1处开始遍历
	return 0;
}