/**
 * 算法思想：枚举法（Enumeration / Brute-Force Search）
 * 核心逻辑：定义明确的解空间，按序穷举每一个候选解，并依据判定准则进行验证。
 * 时间复杂度：O((R - L + 1) * log10(R))，在 1 秒内可轻松通过 10^4 规模。
 */

#include <iostream>
using namespace std;

int main() {
    // 1. 输入数据：定义枚举的起止边界
    int L, R;
    cin >> L >> R;

    // 2. 累加器：用于记录满足条件的解（数字2出现的总次数）
    int ans = 0;

    // 3. 确定解空间与枚举顺序：
    //    枚举对象：区间 [L, R] 内的每一个离散整数
    //    枚举顺序：从小到大线性自增，保证“不重、不漏”
    for (int i = L; i <= R; i++) {

        // 4. 保护枚举状态：
        //    i 是控制遍历进度的外层坐标，不可被直接修改；
        //    使用临时变量 t 拷贝 i 的值，用于接下来的独立检验。
        int t = i;

        // 5. 验证准则（“拿来试”的具体过程）：
        //    通过短除法逐位拆解当前整数 t，检查是否命中目标条件。
        while (t > 0) {
            // (1) 检验当前最低位是否为 2
            if (t % 10 == 2) {
                ans++;
            }
            // (2) 剥离最低位，推进到更高一位（相当于整体右移一位）
            t = t / 10;
        }
    }

    // 6. 输出最终统计的最优/目标解
    cout << ans << endl;

    return 0;
}